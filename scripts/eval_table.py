"""Generate docs/evaluation.md from the result JSON files.

The table in the report is generated, never hand-typed, so a late change to
tau cannot leave stale numbers behind.

  python -m scripts.eval_table
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

EVAL = Path("data/eval")
METRICS = Path("data/metrics/latency.jsonl")
OUT = Path("docs/evaluation.md")

REPORTED_SPLIT = "query / bounding_box_test"
TARGET_TOP1 = 0.80


def load(name: str):
    p = EVAL / name
    return json.loads(p.read_text()) if p.exists() else None


def pct(x) -> str:
    return f"{x * 100:.1f}%" if isinstance(x, (int, float)) else "—"


def main() -> None:
    L: list[str] = ["# Evaluation results", "",
                    "Generated by `scripts/eval_table.py`. Do not edit by hand.", ""]

    # ---- Tier 1 ----
    tier1 = load("market1501_results.json") or []
    L += ["## Tier 1 — Market-1501, embedder alone", "",
          f"Reported on **{REPORTED_SPLIT}**. Cross-domain: the weights are trained",
          "on MSMT17 and evaluated on Market-1501, so the comparison is the",
          "cross-domain table in the OSNet-AIN paper, **not** the same-domain ~94%",
          "rank-1 figures that assume training on Market-1501.", "",
          "| Weights | Model | Rank-1 | Rank-5 | mAP | Queries |",
          "|---|---|---|---|---|---|"]
    for r in sorted(tier1, key=lambda r: -r.get("rank1", 0)):
        L.append(f"| `{r['weights']}` | {r['model']} | {pct(r['rank1'])} | "
                 f"{pct(r['rank5'])} | {pct(r['mAP'])} | {r['n_queries']} |")
    if not tier1:
        L.append("| _not yet run_ | | | | | |")
    if len(tier1) >= 2:
        best = max(tier1, key=lambda r: r["rank1"])
        L += ["", f"**{best['model']}** wins, so it is the configured default."]

    # ---- Tier 2 ----
    sweep = load("tau_sweep.json")
    L += ["", "## Tier 2 — through the real search path", ""]
    if sweep:
        split = sweep.get("tuning_split", "unknown")
        leaked = split in REPORTED_SPLIT or "test" in split
        L += [f"Tuned on **{split}** — {'**LEAKED: same identities as the reported split**' if leaked else 'identities disjoint from the reported split'}.",
              "",
              f"{sweep.get('n_queries', '?')} held-out cross-camera queries against "
              f"{sweep.get('gallery_tracklets', '?')} gallery tracklets from "
              f"{sweep.get('gallery_identities', '?')} identities, using "
              f"`{sweep.get('weights', '?')}`.", "",
              "| tau | Top-1 | Top-5 | Wrong matches passing tau |",
              "|---|---|---|---|"]
        for r in sweep["rows"]:
            mark = " **(chosen)**" if r["tau"] == sweep.get("best_tau") else ""
            L.append(f"| {r['tau']:.2f}{mark} | {pct(r['top1'])} | "
                     f"{pct(r['top5'])} | {r['false_positives']} |")
        best_top1 = max(r["top1"] for r in sweep["rows"])
        L += ["",
              f"Best top-1 is {pct(best_top1)}, against the product spec's target of "
              f"{pct(TARGET_TOP1)}: "
              f"**{'met' if best_top1 >= TARGET_TOP1 else 'NOT met'}**.",
              "",
              "The false-positive column counts non-matching tracklets inside a",
              "top-5 window, so ~3 per query is its ceiling; read it as a trend,",
              "not an absolute rate."]
    else:
        L.append("_not yet run_")

    # ---- Tier 3 ----
    own = load("own_footage_results.json") or []
    L += ["", "## Tier 3 — own footage", "",
          "One subject. Every row states the distractor count it was measured",
          "against: with no distractors, top-1 is 100% by construction.", "",
          "| Run | Weights | tau | Top-1 | Top-5 | Queries | Distractors | FPs |",
          "|---|---|---|---|---|---|---|---|"]
    for r in own:
        flag = " ⚠️ vacuous" if r.get("vacuous") else ""
        L.append(f"| {r['label']}{flag} | `{r.get('weights', '?')}` | {r['tau']:.2f} | "
                 f"{pct(r['top1'])} | {pct(r['top5'])} | {r['n_queries']} | "
                 f"{r['distractors']} | {r['false_positives']} |")
    if not own:
        L += ["| _not yet run — needs filmed footage and a labelled ground-truth CSV_ | | | | | | | |",
              "",
              "Blocked on filming: two spots, several outfits, one dim-light pass,",
              "with reference photos taken separately from the clips."]

    # ---- R8 ----
    L += ["", "## R8 — live latency", ""]
    if METRICS.exists():
        rows = [json.loads(x) for x in METRICS.read_text().splitlines() if x.strip()]
        live = [r["latency_s"] for r in rows if r.get("live")]
        if live:
            L += [f"{len(live)} live measurements. Median "
                  f"{statistics.median(live):.2f}s, worst {max(live):.2f}s, against a",
                  f"10s requirement: **{'PASS' if max(live) <= 10 else 'FAIL'}**.", "",
                  "Recorded-file ingestion is excluded: its timestamps are the",
                  "footage's own, so 'latency' there is the age of the file."]
        else:
            L.append("_no live measurements yet_")
    else:
        L.append("_no measurements yet; run a live walk-through_")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
